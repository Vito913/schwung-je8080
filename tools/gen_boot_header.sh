#!/usr/bin/env bash
# Assemble src/boot/je8080_boot.S and regenerate src/dsp/je8080_boot_block.h.
# Needs binutils-h8300-hms (apt install binutils-h8300-hms). The module build
# does not: the generated header is committed.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
h8300-hitachi-coff-as -o "$TMP/boot.o" "$ROOT/src/boot/je8080_boot.S"
h8300-hitachi-coff-ld -mh8300s -e 0 -Ttext=0 -o "$TMP/boot.coff" "$TMP/boot.o"
h8300-hitachi-coff-objcopy -O binary "$TMP/boot.coff" "$TMP/boot.bin"
python3 - "$TMP/boot.bin" "$ROOT/src/dsp/je8080_boot_block.h" <<'PY'
import sys
data = open(sys.argv[1], 'rb').read()
out = ["/* GENERATED by tools/gen_boot_header.sh from src/boot/je8080_boot.S -- do not edit. */",
       "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
       "namespace je8080 {",
       f"static const size_t kBootBlockLen = {len(data)};",
       "static const uint8_t kBootBlock[] = {"]
for i in range(0, len(data), 16):
    out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i+16]) + ",")
out += ["};", "}  // namespace je8080", ""]
open(sys.argv[2], 'w').write("\n".join(out))
print(f"{len(data)} bytes -> {sys.argv[2]}")
PY
