#!/usr/bin/env bash
# Assemble src/boot/je8080_boot.S and regenerate src/dsp/je8080_boot_block.h.
# Needs binutils-h8300-hms (apt install binutils-h8300-hms). The module build
# does not: the generated header is committed.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
# Assemble twice with different .org gap fill. Bytes that differ are gaps,
# which become RTS (0x54 0x70): an unknown boot-block call then returns.
for fill in 0x00 0xff; do
    sed "s/^\(\s*\.org\s\+0x[0-9A-Fa-f]\+\)\s*$/\1, $fill/" "$ROOT/src/boot/je8080_boot.S" > "$TMP/boot_$fill.S"
    h8300-hitachi-coff-as -o "$TMP/boot_$fill.o" "$TMP/boot_$fill.S"
    h8300-hitachi-coff-ld -mh8300s -e 0 -Ttext=0 -o "$TMP/boot_$fill.coff" "$TMP/boot_$fill.o" 2>/dev/null
    h8300-hitachi-coff-objcopy -O binary "$TMP/boot_$fill.coff" "$TMP/boot_$fill.bin"
done
python3 - "$TMP/boot_0x00.bin" "$TMP/boot_0xff.bin" "$ROOT/src/dsp/je8080_boot_block.h" <<'PY'
import sys
a = open(sys.argv[1], 'rb').read(); b = open(sys.argv[2], 'rb').read()
assert len(a) == len(b), (len(a), len(b))
data = bytearray(a)
gaps = 0
for i in range(len(data)):
    if a[i] != b[i]:
        data[i] = 0x54 if i % 2 == 0 else 0x70
        gaps += 1
data = bytes(data)
print(f"{gaps} gap bytes filled with RTS")
sys.argv = [sys.argv[0], None, sys.argv[3]]
out = ["/* GENERATED by tools/gen_boot_header.sh from src/boot/je8080_boot.S -- do not edit. */",
       "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
       "namespace je8080 {",
       f"static const size_t kBootBlockLen = {len(data)};",
       "static const uint8_t kBootBlock[] = {"]
for i in range(0, len(data), 16):
    out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i+16]) + ",")
out += ["};", "}  // namespace je8080", ""]
open(sys.argv[2], 'w').write("\n".join(out))
print(f"{len(data)} bytes -> {sys.argv[2]}")
PY
